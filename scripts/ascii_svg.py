#!/usr/bin/env python3
"""
Photo -> self-building ASCII terminal (animated SVG) for a GitHub profile README.

    python scripts/ascii_svg.py photo.jpg --out assets/terminal-ascii.svg

Best input: front-facing, plain background, good contrast, face filling the frame.
Run it once locally (needs Pillow). Commit the SVG; it is not regenerated by CI.
"""
import argparse
import html
from pathlib import Path

from PIL import Image, ImageEnhance, ImageFilter, ImageOps

RAMP = " .:-=+*#%@"   # light -> dense
COARSE = " .:"        # first "rough" pass of the build animation
FONT = 'ui-monospace,SFMono-Regular,Menlo,Consolas,"DejaVu Sans Mono",monospace'

CSS = """
text{font-family:%FONT%}
.t{font-size:13px;fill:#d6d6d6}
.g{font-size:%FS%px;fill:%COLOR%}
.c{font-size:%FS%px;fill:%COLOR%;fill-opacity:.55;animation:coarse 1.2s linear both}
.f{animation:fin .5s ease-out both}
.cur{opacity:0;animation:blink 1s steps(1) infinite}
.scan{opacity:0}
@keyframes coarse{0%{opacity:0}15%{opacity:.85}70%{opacity:.85}100%{opacity:0}}
@keyframes fin{from{opacity:0}to{opacity:1}}
@keyframes blink{0%{opacity:1}50%{opacity:0}}
@keyframes scan{0%{transform:translateY(0);opacity:.7}90%{opacity:.7}100%{transform:translateY(%TRAVEL%px);opacity:0}}
"""


def image_to_rows(path, cols, cw, lh, invert, contrast, gamma=1.0):
    img = Image.open(path).convert("L")
    w, h = img.size
    rows = max(1, round(cols * (h / w) * cw / lh))
    img = ImageOps.autocontrast(img, cutoff=2)
    img = ImageEnhance.Contrast(img).enhance(contrast)
    img = img.resize((cols, rows), Image.LANCZOS)
    img = img.filter(ImageFilter.UnsharpMask(radius=1, percent=120, threshold=2))
    px = img.load()

    border = (
        [px[x, 0] for x in range(cols)] + [px[x, rows - 1] for x in range(cols)]
        + [px[0, y] for y in range(rows)] + [px[cols - 1, y] for y in range(rows)]
    )
    if invert is None:  # light background -> dark features become the dense characters
        invert = sum(border) / len(border) > 127

    fine, coarse = [], []
    for y in range(rows):
        f, c = [], []
        for x in range(cols):
            v = px[x, y] / 255
            level = 1 - v if invert else v
            level = max(0.0, (level - 0.08) / 0.92)  # kill faint background noise
            level = level ** gamma                    # <1 lifts mid-tones (skin), >1 darkens
            f.append(RAMP[min(len(RAMP) - 1, int(level * len(RAMP)))])
            c.append(COARSE[min(len(COARSE) - 1, int(level * len(COARSE)))])
        fine.append("".join(f).rstrip())
        coarse.append("".join(c).rstrip())
    return fine, coarse, rows, invert


def esc(s):
    return html.escape(s, quote=False)


def build_svg(fine, coarse, rows, cw, lh, a):
    pad, top = 24, 78
    panel_w = a.cols * cw
    W = round(panel_w + pad * 2)
    H = round(top + rows * lh + 44)
    base, step = 2.2, a.row_delay
    dur = rows * step + 1.2

    prompt = f"{a.user}@{a.host} ~ $ ./whoami"
    char_w = 7.8  # 13px monospace
    tw = len(prompt) * char_w
    n = len(prompt)
    values = ";".join(f"{k * char_w + (12 if k == n else 0):.1f}" for k in range(n + 1))
    key_times = ";".join(f"{k / n:.4f}" for k in range(n + 1))

    css = (CSS.replace("%FONT%", FONT).replace("%FS%", str(a.font_size))
           .replace("%COLOR%", a.color).replace("%TRAVEL%", str(round(rows * lh))))
    if a.static:
        css = CSS.split("@keyframes")[0].replace("%FONT%", FONT).replace("%FS%", str(a.font_size)) \
            .replace("%COLOR%", a.color)

    o = []
    o.append(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" '
             f'xml:space="preserve" role="img" aria-label="ASCII portrait building itself in a terminal">')
    o.append(f"<style>{css}</style>")
    o.append(f'<defs><clipPath id="tp"><rect x="{pad}" y="46" height="24" width="{tw + 12:.1f}">')
    if not a.static:
        o[-1] = o[-1].replace(f'width="{tw + 12:.1f}">', 'width="0">')
        o.append(f'<animate attributeName="width" values="{values}" keyTimes="{key_times}" '
                 f'calcMode="discrete" begin="0.3s" dur="1.6s" fill="freeze"/>')
    o.append("</rect></clipPath></defs>")

    # window chrome
    o.append(f'<rect x=".5" y=".5" width="{W - 1}" height="{H - 1}" rx="12" fill="#0b0b0b" stroke="#2a2a2a"/>')
    o.append(f'<path d="M1 36H{W - 1}" stroke="#1f1f1f"/>')
    for i, c in enumerate(("#e0e0e0", "#8a8a8a", "#4a4a4a")):
        o.append(f'<circle cx="{22 + i * 20}" cy="18" r="6" fill="{c}"/>')
    o.append(f'<text class="t" x="{W / 2:.0f}" y="22" text-anchor="middle" fill="#8a8a8a" '
             f'style="font-size:12px;fill:#8a8a8a">{esc(a.user)}@{esc(a.host)}: ~</text>')

    # typed prompt + cursor
    o.append(f'<text class="t" x="{pad}" y="62" clip-path="url(#tp)">{esc(prompt)}</text>')
    if not a.static:
        o.append(f'<rect class="cur" x="{pad + tw + 3:.1f}" y="49" width="8" height="15" fill="{a.color}" '
                 f'style="animation-delay:1.9s"/>')

    # ASCII rows
    o.append('<g>')
    for i, (f, c) in enumerate(zip(fine, coarse)):
        y = round(top + (i + 1) * lh, 1)
        if not f.strip():
            continue
        # textLength pins every row to exact column widths, whatever monospace font the viewer has
        tl = f'textLength="{len(f) * cw:.1f}" lengthAdjust="spacing"'
        if a.static:
            o.append(f'<text class="g" x="{pad}" y="{y}" {tl}>{esc(f)}</text>')
        else:
            d = base + i * step
            tlc = f'textLength="{len(c) * cw:.1f}" lengthAdjust="spacing"'
            o.append(f'<text class="c" x="{pad}" y="{y}" {tlc} style="animation-delay:{d:.2f}s">{esc(c)}</text>')
            o.append(f'<text class="g f" x="{pad}" y="{y}" {tl} style="animation-delay:{d + 0.9:.2f}s">{esc(f)}</text>')
    o.append("</g>")

    if not a.static:
        o.append(f'<rect class="scan" x="{pad}" y="{top}" width="{panel_w:.0f}" height="2" fill="{a.color}" '
                 f'style="animation:scan {dur:.2f}s linear {base}s forwards"/>')
        end = base + dur + 0.4
        o.append(f'<text class="t f" x="{pad}" y="{H - 16}" style="animation-delay:{end:.2f}s">'
                 f'{esc(a.user)}@{esc(a.host)} ~ $</text>')
        cx = pad + (len(a.user) + len(a.host) + 6) * char_w + 4
        o.append(f'<rect class="cur" x="{cx:.1f}" y="{H - 28}" width="8" height="15" fill="{a.color}" '
                 f'style="animation-delay:{end:.2f}s"/>')
    o.append("</svg>")
    return "\n".join(o), W, H


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("photo")
    p.add_argument("--out", default="assets/terminal-ascii.svg")
    p.add_argument("--cols", type=int, default=80, help="ASCII width in characters")
    p.add_argument("--font-size", type=float, default=7)
    p.add_argument("--user", default="abhishek")
    p.add_argument("--host", default="github")
    p.add_argument("--color", default="#d0d0d0")
    p.add_argument("--invert", choices=["auto", "yes", "no"], default="auto",
                   help="yes = dark pixels become dense characters (use for light backgrounds)")
    p.add_argument("--contrast", type=float, default=1.3)
    p.add_argument("--gamma", type=float, default=1.0, help="<1 = denser mid-tones (fills in faces)")
    p.add_argument("--row-delay", type=float, default=0.045, help="seconds between rows")
    p.add_argument("--static", action="store_true", help="no animation (for previewing the final art)")
    a = p.parse_args()

    cw, lh = a.font_size * 0.6, a.font_size * 1.1
    inv = {"auto": None, "yes": True, "no": False}[a.invert]
    fine, coarse, rows, used_inv = image_to_rows(a.photo, a.cols, cw, lh, inv, a.contrast, a.gamma)
    svg, W, H = build_svg(fine, coarse, rows, cw, lh, a)

    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(svg, encoding="utf-8")
    print(f"wrote {out}  {W}x{H}px  {len(svg) / 1024:.0f} KB  invert={used_inv}")


if __name__ == "__main__":
    main()
